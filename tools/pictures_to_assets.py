"""Turn downloaded word photos into app assets: 640 px JPEGs plus a credits file.

Usage: python3 -I tools/pictures_to_assets.py <download dir> [picture-to-skip ...]

Reads <download dir>/pictures.json (written by fetch_pictures.py), shrinks each image with macOS `sips`
into app/src/main/assets/pictures/<code points>.jpg and writes app/src/main/assets/pictures/credits.tsv:
picture<TAB>file<TAB>article<TAB>artist<TAB>licence<TAB>source page. Pictures given as arguments are left
out (photos rejected on review); the app then shows their emoji instead.
"""
import html, json, os, re, shutil, subprocess, sys

src = sys.argv[1]
skip = set(sys.argv[2:])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'app', 'src', 'main', 'assets', 'pictures')
entries = json.load(open(os.path.join(src, 'pictures.json'), encoding='utf-8'))

if os.path.isdir(out):
    shutil.rmtree(out)
os.makedirs(out)


def plain(text):
    """Commons puts HTML (links, spans) in the artist field; keep the visible text on one line."""
    text = re.sub(r'<[^>]+>', '', text or '')
    return ' '.join(html.unescape(text).split())


def author(text):
    """A short, readable author credit from Commons' artist field."""
    text = plain(text)
    text = re.sub(r'\s*\(talk\)', '', text)
    text = re.sub(r'^\S+\.(jpe?g|png|svg|tiff?):\s*', '', text, flags=re.I)  # "File.jpg: name"
    text = re.sub(r'^(.+?)\1', r'\1', text)  # "Unknown authorUnknown author"
    if len(text) > 70:
        text = text[:70].rsplit(' ', 1)[0].rstrip(',;') + '…'
    return text


lines = [
    '# Word photos: lead images of English Wikipedia articles, hosted on Wikimedia Commons.',
    '# Generated by tools/pictures_to_assets.py. Each photo keeps its own licence (see the source page).',
    '# picture<TAB>file<TAB>article<TAB>artist<TAB>licence<TAB>source page<TAB>licence link',
    '# The photos are resized and cropped for the app.',
]
kept = 0
for e in entries:
    if e['emoji'] in skip:
        continue
    name = os.path.splitext(e['image'])[0] + '.jpg'
    subprocess.run(
        ['sips', '-s', 'format', 'jpeg', '-s', 'formatOptions', '78', '-Z', '640',
         os.path.join(src, e['image']), '--out', os.path.join(out, name)],
        check=True, capture_output=True,
    )
    fields = [
        e['emoji'], name, e['article'], author(e['artist']) or 'Unknown author', plain(e['license']), e['page'],
        plain(e.get('license_url', '')),
    ]
    lines.append('\t'.join(f.replace('\t', ' ') for f in fields))
    kept += 1

with open(os.path.join(out, 'credits.tsv'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
size = sum(os.path.getsize(os.path.join(out, n)) for n in os.listdir(out))
print(f'{kept} photos, {size // 1024} KB, in {out}')
